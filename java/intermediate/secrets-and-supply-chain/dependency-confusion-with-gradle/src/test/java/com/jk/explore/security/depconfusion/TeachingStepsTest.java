package com.jk.explore.security.depconfusion;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Optional;
import org.junit.jupiter.api.Test;

/** The teaching classes are pure: no Gradle, no repository. */
class TeachingStepsTest {

    @Test
    void versionsCompareNumberByNumber() {
        assertTrue(VersionSteps.ORDER.compare("99.0.0", "1.4.2") > 0);
        assertTrue(VersionSteps.ORDER.compare("1.10", "1.9") > 0);
        assertTrue(VersionSteps.ORDER.compare("1.4.2", "1.4") > 0);
        assertEquals(0, VersionSteps.ORDER.compare("1.4", "1.4.0"));
        assertEquals("99 > 1", VersionSteps.firstDifference("99.0.0", "1.4.2"));
        assertEquals("9 < 10", VersionSteps.firstDifference("1.9", "1.10"));
        assertEquals("equal", VersionSteps.firstDifference("1.4", "1.4.0"));
    }

    @Test
    void anOpenRangeTakesTheHighestAtOrAboveItsLowerBound() {
        assertEquals("1.4", VersionSteps.lowerBound("[1.4,)"));
        assertTrue(VersionSteps.inRange("1.4.2", "[1.4,)"));
        assertFalse(VersionSteps.inRange("1.3.9", "[1.4,)"));
        assertEquals(Optional.of("99.0.0"), VersionSteps.highest(List.of("1.4.2", "99.0.0", "1.0"), "[1.4,)"));
        assertEquals(Optional.empty(), VersionSteps.highest(List.of("1.0"), "[1.4,)"));
        assertThrows(IllegalArgumentException.class, () -> VersionSteps.lowerBound("1.4"));
    }

    @Test
    void aGroupFilterCoversSubgroupsOnlyWhenItSaysSo() {
        assertTrue(GroupFilter.covers("includeGroup", "com.shop", "com.shop"));
        assertFalse(GroupFilter.covers("includeGroup", "com.shop", "com.shop.tools"));
        assertTrue(GroupFilter.covers("includeGroupAndSubgroups", "com.shop", "com.shop.tools"));
        assertFalse(GroupFilter.covers("includeGroupAndSubgroups", "com.shop", "com.shopping"));
        assertFalse(GroupFilter.covers("excludeGroup", "com.shop", "com.shop.tools"));
        assertThrows(IllegalArgumentException.class, () -> GroupFilter.covers("includeModule", "com.shop", "com.shop"));
    }

    @Test
    void checksumsAreReadFromTheMetadataAndComputedFromTheBytes() {
        String sha = Checksums.sha256("abc".getBytes(StandardCharsets.UTF_8));
        assertEquals("ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad", sha);
        String xml = """
                <components>
                   <component group="com.shop" name="pricing" version="1.4.2">
                      <artifact name="pricing-1.4.2.jar">
                         <sha256 value="%s" origin="Generated by Gradle"/>
                      </artifact>
                   </component>
                </components>""".formatted(sha);
        assertEquals(sha, Checksums.listed(xml, "com.shop", "pricing", "1.4.2", "pricing-1.4.2.jar"));
        assertNull(Checksums.listed(xml, "com.shop", "pricing", "99.0.0", "pricing-99.0.0.jar"));
        assertNull(Checksums.listed(xml, "com.shop", "pricing", "1.4.2", "pricing-1.4.2.pom"));
    }
}
