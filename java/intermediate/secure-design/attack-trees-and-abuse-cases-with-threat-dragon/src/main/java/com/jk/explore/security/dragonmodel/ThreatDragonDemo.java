package com.jk.explore.security.dragonmodel;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;
import tools.jackson.databind.JsonNode;
import tools.jackson.databind.json.JsonMapper;
import tools.jackson.databind.node.ArrayNode;
import tools.jackson.databind.node.ObjectNode;

public class ThreatDragonDemo {

    private static final JsonMapper JSON = JsonMapper.builder().build();

    public static void main(String[] args) throws Exception {
        System.out.print(run());
    }

    public static String run() throws Exception {
        StringBuilder out = new StringBuilder();
        try (Dragon dragon = new Dragon()) {
            act1(out);
            act2(out, dragon);
            act3(out, dragon);
            act4(out);
            act5(out, dragon);
        }
        return out.toString();
    }

    private static void line(StringBuilder out, String text) {
        out.append(text).append('\n');
    }

    /** The configurations after 0, 1, 2 ... defences of the plan: the same plan as in the plain project. */
    static List<BankConfig> steps() {
        List<BankConfig> configs = new ArrayList<>();
        BankConfig c = BankConfig.weak();
        configs.add(c);
        for (Planner.Step s : Planner.plan(BankTree.baseline(), Defence.all(), 5_000)) {
            c = c.with(s.defence().configChange());
            configs.add(c);
        }
        return configs;
    }

    private static void act1(StringBuilder out) {
        line(out, "ONE. The tree, as a Threat Dragon model.");
        Node tree = BankTree.baseline();
        Analysis base = Analysis.of(tree);
        line(out, String.format("  the attack tree of the plain project: cheapest way in %,.0f EUR via %s, chance that some way works %.0f%%, 8 abuse cases", base.minCost(), base.cheapestPath(), base.probability() * 100));
        String model = ModelBuilder.json(BankConfig.weak());
        JsonNode diagram = JSON.readTree(model).get("detail").get("diagrams").get(0);
        Map<String, Integer> shapes = new LinkedHashMap<>();
        diagram.get("cells").forEach(c -> shapes.merge(c.get("shape").asString(), 1, Integer::sum));
        line(out, "  the model file for Threat Dragon " + ModelBuilder.VERSION + ": one diagram, " + diagram.get("cells").size() + " cells " + shapes + ", " + ModelChecks.count(model, "Open") + " threats, all Open");
        line(out, "  each abuse case is a threat on the element or flow it hits:");
        for (Cases.Entry e : Cases.all(tree)) {
            line(out, String.format("    %-4s %-23s on %-9s %-6s %s", e.id(), e.stride(), e.element(), e.severity(), e.score()));
        }
        line(out, "  the tree's costs and chances become each threat's severity and score; the AND and OR of the tree stay in the plain project, because a model of flat threats has no place for them");
    }

    static String broken(String model, String how) {
        ObjectNode root = (ObjectNode) JSON.readTree(model);
        JsonNode diagram = root.get("detail").get("diagrams").get(0);
        switch (how) {
            case "no title" -> ((ObjectNode) root.get("summary")).remove("title");
            case "short type" -> ((ObjectNode) diagram).put("diagramType", "x");
            case "no id" -> ((ObjectNode) diagram.get("cells").get(2)).remove("id");
            case "tiny" -> ((ObjectNode) diagram.get("cells").get(2).get("size")).put("width", 5);
            default -> throw new IllegalArgumentException(how);
        }
        return JSON.writerWithDefaultPrettyPrinter().writeValueAsString(root);
    }

    private static void act2(StringBuilder out, Dragon dragon) throws Exception {
        line(out, "TWO. Checked by Threat Dragon's own validator.");
        String model = ModelBuilder.json(BankConfig.weak());
        Map<String, String> files = new LinkedHashMap<>();
        files.put("bank.json", model);
        for (String how : List.of("no title", "short type", "no id", "tiny")) {
            files.put(how.replace(' ', '-') + ".json", broken(model, how));
        }
        Map<String, Dragon.Verdict> verdicts = dragon.validate(files);
        line(out, "  the image " + Dragon.IMAGE.replaceAll("-arm64$", "") + " carries the schema in its editor bundle and the Ajv that checks it; both are used as they are");
        line(out, "  the bank's model: " + (verdicts.get("bank.json").valid() ? "valid" : "invalid " + verdicts.get("bank.json").errors()));
        for (String how : List.of("no title", "short type", "no id", "tiny")) {
            Dragon.Verdict v = verdicts.get(how.replace(' ', '-') + ".json");
            line(out, "  " + how + ": " + (v.valid() ? "valid" : "refused, " + v.errors()));
        }
        line(out, "  the editor refuses a file that fails these checks when it is opened, so a file generated by a program is checked the same way before anyone opens it");
    }

    private static void act3(StringBuilder out, Dragon dragon) throws Exception {
        line(out, "THREE. The plan, step by step, in the file.");
        List<BankConfig> steps = steps();
        Map<String, String> files = new LinkedHashMap<>();
        List<String> models = new ArrayList<>();
        for (int i = 0; i < steps.size(); i++) {
            String m = ModelBuilder.json(steps.get(i));
            models.add(m);
            files.put("step" + i + ".json", m);
        }
        Map<String, Dragon.Verdict> verdicts = dragon.validate(files);
        List<String> defences = new ArrayList<>(List.of("(none)"));
        Planner.plan(BankTree.baseline(), Defence.all(), 5_000).forEach(s -> defences.add(s.defence().id()));
        List<AbuseCase> cases = AbuseCase.all();
        for (int i = 0; i < steps.size(); i++) {
            BankConfig config = steps.get(i);
            long failing = cases.stream().filter(c -> !c.passes(config)).count();
            line(out, String.format("  step %d %-8s open threats in the file %d, abuse cases failing %d, validator: %s", i, defences.get(i), ModelChecks.count(models.get(i), "Open"), failing, verdicts.get("step" + i + ".json").valid() ? "valid" : "invalid"));
        }
        List<String> before = ModelChecks.statuses(models.get(0));
        List<String> after = ModelChecks.statuses(models.get(models.size() - 1));
        List<String> changed = new ArrayList<>();
        for (int i = 0; i < before.size(); i++) {
            if (!before.get(i).equals(after.get(i))) {
                changed.add(after.get(i));
            }
        }
        line(out, "  after the plan, the threats that changed: " + changed);
        line(out, "  still open: " + after.stream().filter(s -> s.endsWith("Open")).map(s -> s.split(" ")[0]).collect(Collectors.toList()) + "  <- THE SAME TWO CASES AS IN THE PLAIN PROJECT, AN INSIDER AND A LIBRARY FLAW");
        line(out, "  the file and the tests agree because both come from the same configuration; the file is the picture of the tests, and it is what a reviewer opens");
    }

    private static String mutate(String model, String how) {
        ObjectNode root = (ObjectNode) JSON.readTree(model);
        ArrayNode cells = (ArrayNode) root.get("detail").get("diagrams").get(0).get("cells");
        switch (how) {
            case "no mitigation" -> {
                for (JsonNode c : cells) {
                    if (c.get("data").has("threats")) {
                        for (JsonNode t : c.get("data").get("threats")) {
                            if (t.get("status").asString().equals("Mitigated")) {
                                ((ObjectNode) t).put("mitigation", "");
                                return write(root);
                            }
                        }
                    }
                }
            }
            case "stale flag" -> {
                for (JsonNode c : cells) {
                    if (c.get("data").get("hasOpenThreats").asBoolean()) {
                        ((ObjectNode) c.get("data")).put("hasOpenThreats", false);
                        return write(root);
                    }
                }
            }
            case "lost end" -> {
                for (JsonNode c : cells) {
                    if (c.get("shape").asString().equals("flow")) {
                        ((ObjectNode) c.get("target")).put("cell", "00000000-0000-0000-0000-000000000000");
                        return write(root);
                    }
                }
            }
            case "bad count" -> ((ObjectNode) root.get("detail")).put("threatTop", 3);
            default -> throw new IllegalArgumentException(how);
        }
        return write(root);
    }

    private static String write(JsonNode root) {
        return JSON.writerWithDefaultPrettyPrinter().writeValueAsString(root);
    }

    private static void act4(StringBuilder out) {
        line(out, "FOUR. Checks the schema cannot make.");
        List<BankConfig> steps = steps();
        String start = ModelBuilder.json(steps.get(0));
        String end = ModelBuilder.json(steps.get(steps.size() - 1));
        line(out, "  rules over the file: complete threats, known status and severity, a STRIDE type, a mitigated threat names its defence, the open flag of a cell matches its threats, flows end at cells that exist, threatTop is the highest number, every abuse case has a threat");
        line(out, "  the model before the plan: " + ModelChecks.check(start).size() + " problems; after the plan: " + ModelChecks.check(end).size());
        for (String how : List.of("no mitigation", "stale flag", "lost end", "bad count")) {
            List<ModelChecks.Problem> problems = ModelChecks.check(mutate(end, how));
            line(out, "  " + how + ": " + problems.stream().map(p -> p.rule() + " (" + p.where() + ")").collect(Collectors.toList()));
        }
        line(out, "  a file that a program writes can be wrong in ways a schema does not know, and so can a file that people edit in the editor");
    }

    private static void act5(StringBuilder out, Dragon dragon) throws Exception {
        line(out, "FIVE. The editor, and the bill.");
        dragon.startServer();
        Dragon.Reply page = dragon.get("/");
        line(out, "  the editor's server started from the image, with generated keys, on a loopback port: health " + dragon.get("/healthz").status() + ", the page " + page.status() + " titled " + page.body().replaceAll("(?s).*<title>([^<]*)</title>.*", "$1"));
        line(out, "  providers it offers: " + dragon.get("/api/config").body().replaceAll(".*\"data\":", "").replaceAll("[{}\"]", ""));
        line(out, "  its model API without signing in: " + dragon.get("/api/threatmodel/organisation/models").status() + "; a model is opened in the browser from a file, in a local session, and saved back to a file or a repository");
        line(out, "  the threats are flat and typed by STRIDE: cost, chance and the AND and OR of the tree live in the description and the score text, so the tree is kept where it can be calculated");
        line(out, "  the file is JSON with positions and identifiers, which a program can write and a reviewer can diff; the picture is drawn by the editor from it");
        line(out, "  Threat Dragon stores no tests: whether a Mitigated threat is true is what the abuse cases in the code say");
    }
}
