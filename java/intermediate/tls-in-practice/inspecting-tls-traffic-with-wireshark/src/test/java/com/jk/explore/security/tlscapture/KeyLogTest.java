package com.jk.explore.security.tlscapture;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.List;
import org.junit.jupiter.api.Test;

/** The key log format, and the match by client random, with no program. */
class KeyLogTest {

    private static final String ONE = "aa".repeat(32);
    private static final String TWO = "bb".repeat(32);

    private static KeyLog log(String random) {
        return KeyLog.parse(List.of("# SSL/TLS secrets log file, generated by OpenSSL",
                "SERVER_HANDSHAKE_TRAFFIC_SECRET " + random + " " + "01".repeat(48),
                "CLIENT_HANDSHAKE_TRAFFIC_SECRET " + random + " " + "02".repeat(48),
                "CLIENT_TRAFFIC_SECRET_0 " + random + " " + "03".repeat(48),
                "SERVER_TRAFFIC_SECRET_0 " + random + " " + "04".repeat(48),
                "EXPORTER_SECRET " + random + " " + "05".repeat(48)));
    }

    @Test
    void aLineIsALabelAClientRandomAndASecret() {
        KeyLog log = log(ONE);
        assertEquals(5, log.lines().size(), "the comment is not a line");
        KeyLog.Line line = log.line("CLIENT_TRAFFIC_SECRET_0");
        assertEquals(ONE, line.clientRandom());
        assertEquals(96, line.secret().length());
        assertEquals(KeyLog.OPENS.keySet(), new java.util.HashSet<>(log.lines().stream().map(KeyLog.Line::label).toList()));
    }

    @Test
    void aLogOpensOnlyTheConnectionWithItsClientRandom() {
        assertTrue(log(ONE).opens(ONE));
        assertTrue(log(ONE).opens(ONE.toUpperCase()));
        assertFalse(log(ONE).opens(TWO));
        assertTrue(log(ONE).plus(log(TWO)).opens(TWO));
    }

    @Test
    void theClientLinesAreTwo() {
        KeyLog client = log(ONE).only("CLIENT_");
        assertEquals(List.of("CLIENT_HANDSHAKE_TRAFFIC_SECRET", "CLIENT_TRAFFIC_SECRET_0"), client.lines().stream().map(KeyLog.Line::label).toList());
        assertEquals(client, KeyLog.parse(List.of(client.text().split("\n"))), "the text reads back");
    }
}
