"""Write docs/youtube.md (and its .html twin): every project's review and YouTube status,
with totals by level, module and kind, and the playlists.

Generated from docs/youtube-links.json (kept by ytupload.py), docs/youtube-review.json
(the pre-upload review record) and docs/youtube-quality.json (ytquality.py's checks). Run after every upload; ytupload.py does this itself.
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import ytupload as Y  # noqa: E402

DOCS = os.path.join(Y.REPO, "docs")
LEVELS = ("beginner", "intermediate", "advanced")
LEVEL_NAMES = {"beginner": "Beginner", "intermediate": "Intermediate", "advanced": "Advanced"}


def load(name):
    path = os.path.join(DOCS, name)
    return json.load(open(path)) if os.path.exists(path) else {}


def all_level_projects():
    """[(rel, title)] for every project with a YouTube sheet, in learning-path order."""
    return list(Y.all_projects().items())


def module_title(module):
    return module.replace("-", " ").capitalize().replace("Mfa", "MFA").replace("Tls", "TLS")


def kind(rel):
    return "With tools" if "-with-" in rel.split("/")[2] else "Without tools"


def status(rel, reg):
    e = reg.get(rel)
    if not e:
        return "to upload", ""
    vis = e.get("visibility", "")
    if vis == "Public" and e.get("id"):
        return "public", "[▶ Watch](https://youtu.be/%s)" % e["id"]
    return vis.lower() or "unknown", ""


def quality_text(q):
    if not q:
        return "—"
    n = len(q.get("tries", []))
    word = "try" if n == 1 else "tries"
    if q.get("status") == "failed":
        last = (q["tries"][-1].get("problems") or ["?"])[0] if q.get("tries") else "?"
        return "failed after %d %s: %s" % (n, word, last.replace("|", "/"))
    return "%s (%d %s)" % (q.get("status", "?"), n, word)


def main():
    reg, review = load("youtube-links.json"), load("youtube-review.json")
    quality = load("youtube-quality.json")
    projects = all_level_projects()
    order = Y.learning_order()
    out = ["# Security in Java — YouTube Uploads", ""]
    public = [r for r, _ in projects if status(r, reg)[0] == "public"]
    drafts = [r for r, _ in projects if status(r, reg)[0] == "draft"]
    held = [r for r, _ in projects if status(r, reg)[0] == "held"]
    reviewed = [r for r, _ in projects if r in review]
    corrected = [r for r in reviewed if review[r]["status"] == "corrected"]
    out += ["**%d of %d** projects are on YouTube. %d reviewed before upload (%d needed corrections), "
            "%d draft, %d held back for playlist order."
            % (len(public), len(projects), len(reviewed), len(corrected), len(drafts), len(held)), "",
            "Every video is reviewed for technical accuracy before it is uploaded; a correction is made in the "
            "project's `concept.toml` (and code, if the demo printed it), the video is rebuilt, and the fix is "
            "checked in the captions. Videos go up in the order of the [learning path](../java/learning-path.md), "
            "so each playlist lists them in learning order.", "",
            "Generated by `tools/ytupload/make_progress.py` from `docs/youtube-links.json` and "
            "`docs/youtube-review.json`; do not edit by hand.", ""]

    # quality checks
    qs = [quality[r] for r, _ in projects if r in quality]
    tries = sum(len(q.get("tries", [])) for q in qs)
    first = sum(1 for q in qs if q.get("status") == "passed" and len(q.get("tries", [])) == 1)
    out += ["## Quality checks", "",
            "Every video is checked as YouTube serves it before it goes public: each slide's text "
            "against the slide itself, the sound, the length and the thumbnail. A failed check is "
            "fixed and the video uploaded again, at most three times "
            "(`tools/ytupload/ytquality.py`, see section 8 of the [beginner plan](beginner-plan.md)).", "",
            "| Passed | Passed first time | Failed | In progress | Tries in all |",
            "| ---: | ---: | ---: | ---: | ---: |",
            "| %d | %d | %d | %d | %d |" % (
                sum(1 for q in qs if q.get("status") == "passed"), first,
                sum(1 for q in qs if q.get("status") == "failed"),
                sum(1 for q in qs if q.get("status") == "checking"), tries), ""]

    # totals by level
    out += ["## Totals", "", "| Level | On YouTube | Reviewed | Projects |", "| --- | ---: | ---: | ---: |"]
    for lv in LEVELS:
        rs = [r for r, _ in projects if r.startswith(lv + "/")]
        out.append("| %s | %d | %d | %d |" % (LEVEL_NAMES[lv], sum(r in public for r in rs),
                                            sum(r in review for r in rs), len(rs)))
    out += ["| **All** | **%d** | **%d** | **%d** |" % (len(public), len(reviewed), len(projects)), ""]

    # playlists
    out += ["## Playlists", "", "Two per module: the plain-Java videos, and the versions that add a framework or tool.", "",
            "| Playlist | On YouTube | Projects |", "| --- | ---: | ---: |"]
    lists = {}
    for r, _ in projects:
        name = Y.playlist(r.split("/")[1], r.split("/")[2])
        lists.setdefault(name, []).append(r)
    for name, rs in lists.items():
        out.append("| %s | %d | %d |" % (name, sum(r in public for r in rs), len(rs)))
    out.append("")

    # every project, by level and module
    for lv in LEVELS:
        rs = [(r, t) for r, t in projects if r.startswith(lv + "/")]
        if not rs:
            continue
        out += ["## %s" % LEVEL_NAMES[lv], ""]
        modules = list(dict.fromkeys(r.split("/")[1] for r, _ in rs))
        out += ["| Module | Without tools | With tools | On YouTube | Projects |", "| --- | ---: | ---: | ---: | ---: |"]
        for m in modules:
            ms = [r for r, _ in rs if r.split("/")[1] == m]
            out.append("| [%s](#%s) | %d | %d | %d | %d |" % (
                module_title(m), m, sum(kind(r) == "Without tools" for r in ms),
                sum(kind(r) == "With tools" for r in ms), sum(r in public for r in ms), len(ms)))
        out.append("")
        for m in modules:
            out += ['<a id="%s"></a>' % m, "", "### %s" % module_title(m), "",
                    "| # | Video | Kind | Review | Quality | YouTube |", "| ---: | --- | --- | --- | --- | --- |"]
            for r, title in rs:
                if r.split("/")[1] != m:
                    continue
                st, link = status(r, reg)
                rv = review.get(r)
                rtext = "—" if not rv else ("corrected: " + rv["notes"] if rv["status"] == "corrected" else "ok")
                out.append("| %s | [%s](../java/%s/README.md) | %s | %s | %s | %s |" % (
                    order.get(r, 0) + 1 if r in order else "", title.replace("|", "/"), r, kind(r), rtext,
                    quality_text(quality.get(r)), link or st))
            out.append("")
    md = "\n".join(out)
    open(os.path.join(DOCS, "youtube.md"), "w").write(md)
    try:                                       # the .html twin, when the markdown package is present
        import markdown
        body = markdown.markdown(md.replace("(../java/", "(../java/").replace(".md)", ".html)"),
                                 extensions=["tables"])
        html = ("<!DOCTYPE html><html><head><meta charset='utf-8'><title>Security in Java — YouTube Uploads</title>"
                "<style>body{font-family:system-ui,sans-serif;max-width:1100px;margin:2em auto;padding:0 1em;color:#1e293b}"
                "table{border-collapse:collapse;margin:1em 0}td,th{border:1px solid #cbd5e1;padding:4px 8px;"
                "vertical-align:top}th{background:#f1f5f9}</style></head><body>" + body + "</body></html>")
        open(os.path.join(DOCS, "youtube.html"), "w").write(html)
    except ImportError:
        pass
    print("docs/youtube.md: %d of %d on YouTube, %d reviewed" % (len(public), len(projects), len(reviewed)))


if __name__ == "__main__":
    main()
